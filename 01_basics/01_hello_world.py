# ============================================================
# 📘 Lesson 1: Hello World & the print() Function
# ============================================================
# The print() function is how Python displays output to the screen.
# It's the very first thing every programmer learns!
# ============================================================

# --- Your First Program ---
# print() displays whatever you put inside the parentheses
print("Hello, World!")

# --- Printing Different Things ---
print("My name is Amitesh")
print("I am learning Python!")
print("This is my first program 🎉")

# --- Printing Numbers ---
# You can print numbers without quotes
print(42)
print(3.14)

# --- Printing Multiple Items ---
# Use commas to print multiple things (they get separated by spaces)
print("My age is", 25)
print("Python", "is", "fun!")

# --- Empty print() ---
# An empty print() creates a blank line
print()
print("After a blank line!")

# --- Using end= parameter ---
# By default, print() adds a new line at the end
# You can change this with the end= parameter
print("Hello", end=" ")  # This won't go to next line
print("World!")           # This continues on the same line

# --- Using sep= parameter ---
# sep= changes the separator between items (default is space)
print("Python", "Java", "JavaScript", sep=" | ")
print("2026", "07", "06", sep="-")

